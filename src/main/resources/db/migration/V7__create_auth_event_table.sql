CREATE TABLE auth_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    account_id BIGINT,
    event_type VARCHAR(50) NOT NULL,
    result VARCHAR(20) NOT NULL,
    reason_code VARCHAR(50),
    identifier_hash CHAR(64),
    ip_address INET,
    user_agent VARCHAR(512),
    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_auth_event PRIMARY KEY (id),

    CONSTRAINT fk_auth_event_account FOREIGN KEY (account_id) REFERENCES account (id),

    -- 인증/인가 감사 이벤트의 taxonomy를 고정해 임의 문자열 이벤트가 쌓이지 않게 합니다.
    CONSTRAINT chk_auth_event_type CHECK (
        event_type IN (
            'ACCOUNT_SIGN_UP',
            'PASSWORD_LOGIN',
            'LOGOUT',
            'TOKEN_REFRESH',
            'PASSWORD_CHANGE',
            'PASSWORD_CHANGE_REQUIREMENT',
            'ROLE_CHANGE'
        )
    ),
    -- 성공/실패는 query와 운영 지표가 공유하는 최상위 분류입니다.
    CONSTRAINT chk_auth_event_result CHECK (result IN ('SUCCESS', 'FAILURE')),
    -- reason_code는 event_type과 같은 의미를 반복하지 않고 같은 흐름 안의 세부 원인만 담습니다.
    CONSTRAINT chk_auth_event_reason_not_event_type CHECK (
        reason_code IS NULL OR reason_code <> event_type
    ),
    -- 원본 식별자를 저장하지 않고 실패 시도를 묶어 추적합니다.
    CONSTRAINT chk_auth_event_identifier_hash CHECK (
        identifier_hash IS NULL OR identifier_hash ~ '^[0-9a-f]{64}$'
    ),
    -- metadata는 event별 허용 key를 담는 JSON object로만 사용합니다.
    CONSTRAINT chk_auth_event_metadata_object CHECK (
        jsonb_typeof(metadata) = 'object'
    )
);

-- account별 보안/인증 이력을 최신순으로 확인할 때 사용합니다.
CREATE INDEX idx_auth_event_account_occurred_at
    ON auth_event (account_id, occurred_at DESC);

-- 운영 감사 화면이나 보관 정책이 전체 이벤트를 시간순으로 조회할 때 사용합니다.
CREATE INDEX idx_auth_event_occurred_at
    ON auth_event (occurred_at DESC);

-- 로그인 실패처럼 account가 특정되지 않은 식별자 기반 이벤트를 묶어 추적합니다.
CREATE INDEX idx_auth_event_identifier_occurred_at
    ON auth_event (identifier_hash, occurred_at DESC)
    WHERE identifier_hash IS NOT NULL;
