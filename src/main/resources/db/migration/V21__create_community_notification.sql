-- Community 대화와 같은 transaction에서 저장되는 채널 중립 inbox를 추가합니다.
CREATE TABLE notification_inbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL,
    recipient_account_public_id UUID NOT NULL,
    actor_account_public_id UUID NOT NULL,
    type VARCHAR(40) NOT NULL,
    source_content_public_id UUID NOT NULL,
    post_public_id UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    read_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT pk_notification_inbox PRIMARY KEY (id),
    CONSTRAINT uk_notification_inbox_public_id UNIQUE (public_id),
    CONSTRAINT uk_notification_inbox_source_recipient UNIQUE (recipient_account_public_id, source_content_public_id),
    CONSTRAINT fk_notification_inbox_recipient FOREIGN KEY (recipient_account_public_id) REFERENCES account(public_id) ON DELETE RESTRICT,
    CONSTRAINT fk_notification_inbox_actor FOREIGN KEY (actor_account_public_id) REFERENCES account(public_id) ON DELETE RESTRICT,
    CONSTRAINT chk_notification_inbox_type CHECK (type IN ('COMMUNITY_COMMENT', 'COMMUNITY_REPLY')),
    CONSTRAINT chk_notification_inbox_not_self CHECK (recipient_account_public_id <> actor_account_public_id),
    CONSTRAINT chk_notification_inbox_version CHECK (version >= 0),
    CONSTRAINT chk_notification_inbox_time CHECK (updated_at >= created_at)
);

CREATE INDEX idx_notification_inbox_recipient ON notification_inbox (recipient_account_public_id, created_at DESC, id DESC);
CREATE INDEX idx_notification_inbox_unread ON notification_inbox (recipient_account_public_id, created_at DESC, id DESC) WHERE read_at IS NULL;
