CREATE TABLE account_verification_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    account_id BIGINT NOT NULL,
    purpose VARCHAR(50) NOT NULL,
    delivery_channel VARCHAR(20) NOT NULL,
    recipient_normalized VARCHAR(254) NOT NULL,
    token_hash CHAR(64) NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    last_sent_at TIMESTAMPTZ NOT NULL,
    send_count INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_account_verification_token PRIMARY KEY (id),

    CONSTRAINT fk_account_verification_token_account FOREIGN KEY (account_id) REFERENCES account (id),

    CONSTRAINT uk_account_verification_token_hash UNIQUE (token_hash),

    CONSTRAINT chk_account_verification_token_purpose CHECK (purpose IN ('EMAIL_VERIFICATION')),
    CONSTRAINT chk_account_verification_token_delivery_channel CHECK (delivery_channel IN ('EMAIL')),
    -- 인증 token 원문은 저장하지 않고 SHA-256 hex hash만 저장합니다.
    CONSTRAINT chk_account_verification_token_hash CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_account_verification_token_expires_at CHECK (expires_at > issued_at),
    CONSTRAINT chk_account_verification_token_last_sent_at CHECK (last_sent_at >= issued_at),
    CONSTRAINT chk_account_verification_token_send_count CHECK (send_count >= 1),
    CONSTRAINT chk_account_verification_token_consumed_at CHECK (
        consumed_at IS NULL OR consumed_at >= issued_at
    ),
    CONSTRAINT chk_account_verification_token_revoked_at CHECK (
        revoked_at IS NULL OR revoked_at >= issued_at
    ),
    -- token은 소비와 폐기 중 하나의 terminal state만 가질 수 있습니다.
    CONSTRAINT chk_account_verification_token_terminal_state CHECK (
        consumed_at IS NULL OR revoked_at IS NULL
    ),
    CONSTRAINT chk_account_verification_token_updated_at CHECK (updated_at >= created_at)
);

-- 같은 account/purpose/channel에는 아직 소비되거나 폐기되지 않은 token을 하나만 허용합니다.
CREATE UNIQUE INDEX uk_account_verification_token_open_account_purpose_channel
    ON account_verification_token (account_id, purpose, delivery_channel)
    WHERE consumed_at IS NULL AND revoked_at IS NULL;

-- 현재 조회에는 쓰지 않지만, 만료 token cleanup batch가 생기면 시간 범위 조회에 사용합니다.
CREATE INDEX idx_account_verification_token_expires_at
    ON account_verification_token (expires_at);
