-- 기본 가격은 configuration 판매 기간 안에서 적용 시작일별 이력을 보존합니다.
CREATE TABLE car_configuration_price (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    configuration_id BIGINT NOT NULL,
    effective_from DATE NOT NULL,
    currency_code CHAR(3) NOT NULL DEFAULT 'KRW',
    price_before_tax_benefit BIGINT NOT NULL,
    price_after_tax_benefit BIGINT,
    source_price_label VARCHAR(120),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_car_configuration_price PRIMARY KEY (id),

    CONSTRAINT uk_car_configuration_price_effective_from UNIQUE (configuration_id, effective_from),

    CONSTRAINT fk_car_configuration_price_configuration FOREIGN KEY (configuration_id) REFERENCES car_configuration (id) ON DELETE CASCADE,

    CONSTRAINT chk_car_configuration_price_currency_code CHECK (currency_code ~ '^[A-Z]{3}$'),
    CONSTRAINT chk_car_configuration_price_amount CHECK (
        price_before_tax_benefit >= 0
        AND (price_after_tax_benefit IS NULL OR (
            price_after_tax_benefit >= 0
            AND price_after_tax_benefit <= price_before_tax_benefit
        ))
    ),
    CONSTRAINT chk_car_configuration_price_source_label CHECK (
        source_price_label IS NULL OR BTRIM(source_price_label) <> ''
    ),
    CONSTRAINT chk_car_configuration_price_updated_at CHECK (updated_at >= created_at)
);

-- 선택 품목은 configuration별 code와 적용 시작일로 가격·선택 가능 상태의 이력을 보존합니다.
CREATE TABLE car_configuration_option (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    configuration_id BIGINT NOT NULL,
    code VARCHAR(80) NOT NULL,
    name VARCHAR(160) NOT NULL,
    option_type VARCHAR(20) NOT NULL,
    category VARCHAR(60),
    is_selectable BOOLEAN NOT NULL,
    price_before_tax_benefit BIGINT,
    price_after_tax_benefit BIGINT,
    currency_code CHAR(3) NOT NULL DEFAULT 'KRW',
    included_items JSONB NOT NULL DEFAULT '[]'::JSONB,
    effective_from DATE NOT NULL,
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_car_configuration_option PRIMARY KEY (id),

    CONSTRAINT uk_car_configuration_option_code_effective_from UNIQUE (
        configuration_id,
        code,
        effective_from
    ),

    CONSTRAINT fk_car_configuration_option_configuration FOREIGN KEY (configuration_id) REFERENCES car_configuration (id) ON DELETE CASCADE,

    CONSTRAINT chk_car_configuration_option_code CHECK (BTRIM(code) <> ''),
    CONSTRAINT chk_car_configuration_option_name CHECK (BTRIM(name) <> ''),
    CONSTRAINT chk_car_configuration_option_type CHECK (
        option_type IN ('SINGLE', 'PACKAGE', 'EXTERIOR_COLOR', 'INTERIOR_COLOR')
    ),
    CONSTRAINT chk_car_configuration_option_category CHECK (category IS NULL OR BTRIM(category) <> ''),
    -- 선택 가능 행은 가격을 가지며 선택 불가 전환 행은 이전 가격을 반복하지 않습니다.
    CONSTRAINT chk_car_configuration_option_selectable_price CHECK (
        (is_selectable
            AND price_before_tax_benefit IS NOT NULL
            AND price_before_tax_benefit >= 0
            AND (price_after_tax_benefit IS NULL OR (
                price_after_tax_benefit >= 0
                AND price_after_tax_benefit <= price_before_tax_benefit
            )))
        OR (NOT is_selectable
            AND price_before_tax_benefit IS NULL
            AND price_after_tax_benefit IS NULL)
    ),
    CONSTRAINT chk_car_configuration_option_currency_code CHECK (currency_code ~ '^[A-Z]{3}$'),
    CONSTRAINT chk_car_configuration_option_included_items CHECK (JSONB_TYPEOF(included_items) = 'array'),
    CONSTRAINT chk_car_configuration_option_display_order CHECK (display_order >= 0),
    CONSTRAINT chk_car_configuration_option_updated_at CHECK (updated_at >= created_at)
);

-- 이 테이블을 사용하는 첫 목록·상세 조회 경로만 보조 index로 추가합니다.
CREATE INDEX idx_car_option_configuration
    ON car_configuration_option (configuration_id, display_order);
