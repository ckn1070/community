-- 인증 행은 기술 변형 하나의 휠·카메라·온도 조건별 효율·배출·주행거리를 보존합니다.
CREATE TABLE car_certification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    vehicle_variant_id BIGINT NOT NULL,
    condition_code VARCHAR(100) NOT NULL,
    condition_name VARCHAR(180) NOT NULL,
    certification_type VARCHAR(16) NOT NULL,
    certification_standard VARCHAR(32) NOT NULL,
    temperature_condition VARCHAR(12),
    wheel_size_inch NUMERIC(4, 1),
    tire_specification VARCHAR(80),
    built_in_camera BOOLEAN NOT NULL DEFAULT FALSE,
    curb_weight_kg INTEGER,
    efficiency_grade SMALLINT,
    city_efficiency NUMERIC(8, 3),
    highway_efficiency NUMERIC(8, 3),
    combined_efficiency NUMERIC(8, 3),
    efficiency_unit VARCHAR(16) NOT NULL,
    city_range_km NUMERIC(8, 2),
    highway_range_km NUMERIC(8, 2),
    combined_range_km NUMERIC(8, 2),
    co2_g_per_km NUMERIC(8, 2),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_car_certification PRIMARY KEY (id),

    CONSTRAINT uk_car_certification_variant_condition UNIQUE (vehicle_variant_id, condition_code),

    CONSTRAINT fk_car_certification_vehicle_variant FOREIGN KEY (vehicle_variant_id) REFERENCES car_vehicle_variant (id) ON DELETE RESTRICT,

    CONSTRAINT chk_car_certification_condition_code CHECK (BTRIM(condition_code) <> ''),
    CONSTRAINT chk_car_certification_condition_name CHECK (BTRIM(condition_name) <> ''),
    CONSTRAINT chk_car_certification_type CHECK (
        certification_type IN ('LIQUID_FUEL', 'ELECTRIC', 'HYDROGEN')
    ),
    CONSTRAINT chk_car_certification_standard CHECK (BTRIM(certification_standard) <> ''),
    CONSTRAINT chk_car_certification_temperature CHECK (
        (certification_type = 'ELECTRIC'
            AND temperature_condition IS NOT NULL
            AND temperature_condition IN ('NORMAL', 'LOW'))
        OR (certification_type <> 'ELECTRIC' AND temperature_condition IS NULL)
    ),
    CONSTRAINT chk_car_certification_positive_values CHECK (
        (wheel_size_inch IS NULL OR wheel_size_inch > 0)
        AND (curb_weight_kg IS NULL OR curb_weight_kg > 0)
        AND (efficiency_grade IS NULL OR efficiency_grade BETWEEN 1 AND 5)
        AND (city_efficiency IS NULL OR city_efficiency > 0)
        AND (highway_efficiency IS NULL OR highway_efficiency > 0)
        AND (combined_efficiency IS NULL OR combined_efficiency > 0)
        AND (city_range_km IS NULL OR city_range_km > 0)
        AND (highway_range_km IS NULL OR highway_range_km > 0)
        AND (combined_range_km IS NULL OR combined_range_km > 0)
        AND (co2_g_per_km IS NULL OR co2_g_per_km >= 0)
    ),
    -- 인증 종류는 단위와 필수 결과를 함께 고정해 서로 다른 연료 체계의 값이 섞이지 않게 합니다.
    CONSTRAINT chk_car_certification_measurement CHECK (
        (certification_type = 'LIQUID_FUEL'
            AND efficiency_unit = 'KM_PER_L'
            AND combined_efficiency IS NOT NULL
            AND co2_g_per_km IS NOT NULL)
        OR (certification_type = 'ELECTRIC'
            AND efficiency_unit = 'KM_PER_KWH'
            AND combined_range_km IS NOT NULL
            AND (temperature_condition = 'LOW' OR combined_efficiency IS NOT NULL))
        OR (certification_type = 'HYDROGEN'
            AND efficiency_unit = 'KM_PER_KG'
            AND combined_efficiency IS NOT NULL
            AND combined_range_km IS NOT NULL)
    ),
    CONSTRAINT chk_car_certification_updated_at CHECK (updated_at >= created_at)
);
