-- 관리자 초대는 account 생성 권한으로 이어지는 bearer token 생명주기입니다.
-- 이 table은 초대 대상, token hash, 수락/회수 terminal state, 감사 추적용 actor를 함께 보존합니다.
CREATE TABLE admin_invitation (
    -- id는 내부 FK용 PK이고 public_id는 API path에 노출할 안정 식별자입니다.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL,

    -- email은 초대 당시 입력 snapshot이고, normalized 값은 중복 open 초대 판단에 사용합니다.
    email VARCHAR(254) NOT NULL,
    email_normalized VARCHAR(254) NOT NULL,

    -- role_id는 수락 시 부여할 auth_role입니다. ROLE_ADMIN 제한은 use case가 검증합니다.
    role_id BIGINT NOT NULL,

    -- raw token은 저장하지 않습니다. 수락 요청의 raw token을 같은 방식으로 hash해 비교합니다.
    token_hash CHAR(64) NOT NULL,

    -- 초대 생성 주체, 수락으로 생성된 account, 명시 회수 주체를 추적합니다.
    invited_by_account_id BIGINT NOT NULL,
    accepted_account_id BIGINT,
    revoked_by_account_id BIGINT,

    -- issued/expires는 token 유효 기간이고, accepted/revoked는 서로 배타적인 terminal state입니다.
    issued_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    accepted_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,

    -- created/updated는 row 자체의 감사 시각입니다. 초대 상태 전이는 accepted/revoked 시각으로 판단합니다.
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- 내부 PK는 외부 API 식별자와 분리합니다.
    CONSTRAINT pk_admin_invitation PRIMARY KEY (id),

    -- public_id는 URL에 노출할 수 있는 초대 식별자이고, token_hash는 raw token 없이 수락 요청을 검증할 lookup key입니다.
    CONSTRAINT uk_admin_invitation_public_id UNIQUE (public_id),
    CONSTRAINT uk_admin_invitation_token_hash UNIQUE (token_hash),

    -- role/account FK는 존재하지 않는 role이나 관련 account가 초대 생명주기에 들어오는 것을 DB에서 막습니다.
    CONSTRAINT fk_admin_invitation_role FOREIGN KEY (role_id) REFERENCES auth_role (id),
    CONSTRAINT fk_admin_invitation_invited_by_account FOREIGN KEY (invited_by_account_id) REFERENCES account (id),
    CONSTRAINT fk_admin_invitation_accepted_account FOREIGN KEY (accepted_account_id) REFERENCES account (id),
    CONSTRAINT fk_admin_invitation_revoked_by_account FOREIGN KEY (revoked_by_account_id) REFERENCES account (id),

    -- SHA-256 lowercase hex 형식만 허용해 token_hash 저장 형태를 고정합니다.
    CONSTRAINT chk_admin_invitation_token_hash CHECK (token_hash ~ '^[0-9a-f]{64}$'),

    -- 만료, 수락, 회수 시각은 token 발급 시각 이전으로 되돌아갈 수 없습니다.
    CONSTRAINT chk_admin_invitation_expires_at CHECK (expires_at > issued_at),
    CONSTRAINT chk_admin_invitation_accepted_at CHECK (
        accepted_at IS NULL OR accepted_at >= issued_at
    ),
    CONSTRAINT chk_admin_invitation_revoked_at CHECK (
        revoked_at IS NULL OR revoked_at >= issued_at
    ),

    -- 수락과 회수는 초대의 terminal state라서 동시에 존재할 수 없습니다.
    CONSTRAINT chk_admin_invitation_terminal_state CHECK (
        accepted_at IS NULL OR revoked_at IS NULL
    ),

    -- 수락 상태와 수락으로 생성된 account 참조는 함께 기록되거나 함께 비어 있어야 합니다.
    CONSTRAINT chk_admin_invitation_accepted_account CHECK (
        (accepted_at IS NULL AND accepted_account_id IS NULL)
        OR (accepted_at IS NOT NULL AND accepted_account_id IS NOT NULL)
    ),

    -- 명시 회수 상태와 회수 주체는 함께 기록되거나 함께 비어 있어야 합니다.
    CONSTRAINT chk_admin_invitation_revoked_actor CHECK (
        (revoked_at IS NULL AND revoked_by_account_id IS NULL)
        OR (revoked_at IS NOT NULL AND revoked_by_account_id IS NOT NULL)
    ),

    -- row 수정 시각이 생성 시각보다 과거가 되지 않게 합니다.
    CONSTRAINT chk_admin_invitation_updated_at CHECK (updated_at >= created_at)
);

-- 같은 email에는 수락 또는 회수되지 않은 open 초대가 하나만 존재할 수 있습니다.
-- 만료된 초대도 accepted/revoked 전에는 open row로 남으므로, 재초대 use case가 먼저 revoked 상태로 닫습니다.
CREATE UNIQUE INDEX uk_admin_invitation_open_email
    ON admin_invitation (email_normalized)
    WHERE accepted_at IS NULL AND revoked_at IS NULL;

-- expires_at index는 만료 후보 조회와 운영 정리 작업의 range 조건을 지원합니다.
CREATE INDEX idx_admin_invitation_expires_at
    ON admin_invitation (expires_at);

-- invited_by_account_id와 issued_at 정렬은 특정 관리자가 보낸 초대 이력 조회 후보 경로입니다.
CREATE INDEX idx_admin_invitation_invited_by_issued_at
    ON admin_invitation (invited_by_account_id, issued_at DESC);

-- PostgreSQL check constraint는 허용값을 append할 수 없으므로 기존 auth_event type constraint를 교체합니다.
ALTER TABLE auth_event
    DROP CONSTRAINT chk_auth_event_type;

-- 이 migration은 event_type 허용 목록만 확장합니다.
-- auth_event metadata의 raw email/token/password 미기록 정책은 application 계층의 event writer가 지킵니다.
ALTER TABLE auth_event
    ADD CONSTRAINT chk_auth_event_type CHECK (
        event_type IN (
            'ACCOUNT_SIGN_UP',
            'PASSWORD_LOGIN',
            'LOGOUT',
            'TOKEN_REFRESH',
            'PASSWORD_CHANGE',
            'PASSWORD_CHANGE_REQUIREMENT',
            'ROLE_CHANGE',
            'EMAIL_VERIFICATION_REQUEST',
            'EMAIL_VERIFICATION_CONFIRM',
            'ADMIN_INVITATION_CREATED',
            'ADMIN_INVITATION_ACCEPTED',
            'ADMIN_INVITATION_REVOKED'
        )
    );
