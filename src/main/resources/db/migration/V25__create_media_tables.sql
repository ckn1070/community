-- Media asset은 private object 검증과 공개 delivery 상태를 소유합니다.
CREATE TABLE media_asset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL,
    owner_account_public_id UUID NOT NULL,
    idempotency_key UUID NOT NULL,
    request_hash CHAR(64) NOT NULL,
    status VARCHAR(30) NOT NULL,
    staging_object_key VARCHAR(512) NOT NULL,
    delivery_object_key VARCHAR(512),
    expected_media_type VARCHAR(50) NOT NULL,
    detected_media_type VARCHAR(50),
    original_byte_size BIGINT,
    delivery_byte_size BIGINT,
    width INTEGER,
    height INTEGER,
    original_checksum_sha256 CHAR(64),
    delivery_checksum_sha256 CHAR(64),
    reservation_expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT pk_media_asset PRIMARY KEY (id),
    CONSTRAINT uk_media_asset_public_id UNIQUE (public_id),
    CONSTRAINT uk_media_asset_request UNIQUE (owner_account_public_id, idempotency_key),
    CONSTRAINT fk_media_asset_owner FOREIGN KEY (owner_account_public_id) REFERENCES account(public_id) ON DELETE RESTRICT,
    CONSTRAINT chk_media_asset_hash CHECK (request_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_media_asset_status CHECK (status IN ('RESERVED','UPLOADED','VERIFYING','READY','REJECTED','DELETE_PENDING','DELETED')),
    CONSTRAINT chk_media_asset_expected_type CHECK (expected_media_type IN ('image/jpeg','image/png','image/gif')),
    CONSTRAINT chk_media_asset_detected_type CHECK (detected_media_type IS NULL OR detected_media_type IN ('image/jpeg','image/png')),
    CONSTRAINT chk_media_asset_original_metadata CHECK (
      (original_byte_size IS NULL AND original_checksum_sha256 IS NULL)
      OR (original_byte_size IS NOT NULL AND original_checksum_sha256 ~ '^[0-9a-f]{64}$')
    ),
    CONSTRAINT chk_media_asset_delivery_metadata CHECK (
      (delivery_object_key IS NULL AND detected_media_type IS NULL AND delivery_byte_size IS NULL
        AND width IS NULL AND height IS NULL AND delivery_checksum_sha256 IS NULL)
      OR (delivery_object_key IS NOT NULL AND detected_media_type IS NOT NULL AND delivery_byte_size IS NOT NULL
        AND width IS NOT NULL AND height IS NOT NULL AND delivery_checksum_sha256 ~ '^[0-9a-f]{64}$')
    ),
    CONSTRAINT chk_media_asset_ready_metadata CHECK (
      status <> 'READY' OR (original_byte_size IS NOT NULL AND delivery_object_key IS NOT NULL)
    ),
    CONSTRAINT chk_media_asset_size CHECK ((original_byte_size IS NULL OR original_byte_size BETWEEN 1 AND 10485760) AND (delivery_byte_size IS NULL OR delivery_byte_size > 0)),
    CONSTRAINT chk_media_asset_pixels CHECK ((width IS NULL AND height IS NULL) OR (width > 0 AND height > 0 AND width::BIGINT * height::BIGINT <= 24000000)),
    CONSTRAINT chk_media_asset_version CHECK (version >= 0),
    CONSTRAINT chk_media_asset_time CHECK (updated_at >= created_at)
);

-- Usage는 검증된 asset과 소비 게시글의 공개 UUID 결속 및 숨김·해제 사실을 보존합니다.
CREATE TABLE media_usage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    asset_id BIGINT NOT NULL,
    consumer_type VARCHAR(30) NOT NULL,
    consumer_public_id UUID NOT NULL,
    status VARCHAR(30) NOT NULL,
    hidden_at TIMESTAMPTZ,
    released_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT pk_media_usage PRIMARY KEY (id),
    CONSTRAINT uk_media_usage_consumer UNIQUE (consumer_type, consumer_public_id, asset_id),
    CONSTRAINT fk_media_usage_asset FOREIGN KEY (asset_id) REFERENCES media_asset(id),
    CONSTRAINT chk_media_usage_consumer CHECK (consumer_type = 'POST_BODY'),
    CONSTRAINT chk_media_usage_status CHECK (status IN ('ACTIVE','HIDDEN_RETAINED','RELEASED')),
    CONSTRAINT chk_media_usage_lifecycle CHECK (
      (status = 'ACTIVE' AND hidden_at IS NULL AND released_at IS NULL)
      OR (status = 'HIDDEN_RETAINED' AND hidden_at IS NOT NULL AND released_at IS NULL)
      OR (status = 'RELEASED' AND released_at IS NOT NULL)
    ),
    CONSTRAINT chk_media_usage_version CHECK (version >= 0),
    CONSTRAINT chk_media_usage_time CHECK (updated_at >= created_at)
);

CREATE UNIQUE INDEX uk_media_usage_active_asset ON media_usage (asset_id) WHERE status <> 'RELEASED';

-- Job은 PostgreSQL transaction 밖 S3 작업의 lease, retry와 terminal 결과를 잃지 않게 합니다.
CREATE TABLE media_job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL,
    asset_id BIGINT,
    type VARCHAR(40) NOT NULL,
    status VARCHAR(30) NOT NULL,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    lease_owner VARCHAR(200),
    lease_until TIMESTAMPTZ,
    next_attempt_at TIMESTAMPTZ,
    last_error_code VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT pk_media_job PRIMARY KEY (id),
    CONSTRAINT uk_media_job_public_id UNIQUE (public_id),
    CONSTRAINT fk_media_job_asset FOREIGN KEY (asset_id) REFERENCES media_asset(id),
    CONSTRAINT chk_media_job_type CHECK (type IN ('VERIFY','DELETE_STAGING','DELETE_DELIVERY','RECONCILE')),
    CONSTRAINT chk_media_job_status CHECK (status IN ('READY','RUNNING','RETRY','DONE','DEAD')),
    CONSTRAINT chk_media_job_attempt CHECK (attempt_count BETWEEN 0 AND 8),
    CONSTRAINT chk_media_job_asset CHECK ((type = 'RECONCILE') OR asset_id IS NOT NULL),
    CONSTRAINT chk_media_job_lease CHECK ((status = 'RUNNING') = (lease_owner IS NOT NULL AND lease_until IS NOT NULL)),
    CONSTRAINT chk_media_job_retry CHECK (status <> 'RETRY' OR (next_attempt_at IS NOT NULL AND last_error_code IS NOT NULL)),
    CONSTRAINT chk_media_job_dead CHECK (status <> 'DEAD' OR last_error_code IS NOT NULL),
    CONSTRAINT chk_media_job_version CHECK (version >= 0),
    CONSTRAINT chk_media_job_time CHECK (updated_at >= created_at)
);

CREATE INDEX idx_media_asset_expiry ON media_asset (status, reservation_expires_at, id);
CREATE INDEX idx_media_job_ready ON media_job (status, next_attempt_at, created_at, id) WHERE status IN ('READY','RETRY');
CREATE INDEX idx_media_job_lease ON media_job (lease_until, id) WHERE status = 'RUNNING';
CREATE UNIQUE INDEX uk_media_job_active_asset_type ON media_job (asset_id, type) WHERE asset_id IS NOT NULL AND status IN ('READY','RUNNING','RETRY');
CREATE UNIQUE INDEX uk_media_job_active_reconcile ON media_job (type) WHERE type = 'RECONCILE' AND asset_id IS NULL AND status IN ('READY','RUNNING','RETRY');
