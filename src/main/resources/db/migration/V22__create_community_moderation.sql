-- Moderation은 Community 내부 row에 결합하지 않고 stable content UUID의 처리 lifecycle을 소유합니다.
CREATE TABLE moderation_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL,
    target_content_public_id UUID NOT NULL,
    target_kind VARCHAR(20) NOT NULL,
    reporter_account_public_id UUID NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'OPEN',
    resolved_by_account_public_id UUID,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resolved_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT pk_moderation_report PRIMARY KEY (id),
    CONSTRAINT uk_moderation_report_public_id UNIQUE (public_id),
    CONSTRAINT fk_moderation_report_reporter FOREIGN KEY (reporter_account_public_id) REFERENCES account(public_id) ON DELETE RESTRICT,
    CONSTRAINT fk_moderation_report_resolver FOREIGN KEY (resolved_by_account_public_id) REFERENCES account(public_id) ON DELETE RESTRICT,
    CONSTRAINT chk_moderation_report_target CHECK (target_kind IN ('POST', 'COMMENT')),
    CONSTRAINT chk_moderation_report_status CHECK (status IN ('OPEN', 'CONTENT_HIDDEN', 'DISMISSED')),
    CONSTRAINT chk_moderation_report_resolution CHECK (
      (status = 'OPEN' AND resolved_by_account_public_id IS NULL AND resolved_at IS NULL)
      OR (status <> 'OPEN' AND resolved_by_account_public_id IS NOT NULL AND resolved_at IS NOT NULL)
    ),
    CONSTRAINT chk_moderation_report_version CHECK (version >= 0),
    CONSTRAINT chk_moderation_report_time CHECK (updated_at >= created_at)
);

CREATE UNIQUE INDEX uk_moderation_report_open_actor_target
ON moderation_report (reporter_account_public_id, target_content_public_id) WHERE status = 'OPEN';
CREATE INDEX idx_moderation_report_status ON moderation_report (status, created_at DESC, id DESC);
