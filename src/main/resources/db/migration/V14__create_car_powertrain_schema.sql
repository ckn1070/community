-- 동력계통은 한 연식이 제공하는 엔진·모터·에너지 조합의 검색 가능한 전체 사양입니다.
CREATE TABLE car_powertrain (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL,
    model_year_id BIGINT NOT NULL,
    code VARCHAR(60) NOT NULL,
    name VARCHAR(120) NOT NULL,
    propulsion_type VARCHAR(12) NOT NULL,
    primary_fuel_type VARCHAR(16) NOT NULL,
    secondary_fuel_type VARCHAR(16),
    drivetrain_type VARCHAR(8) NOT NULL,
    transmission_type VARCHAR(20),
    transmission_gears SMALLINT,
    system_max_power_kw NUMERIC(8, 2),
    system_max_power_ps NUMERIC(8, 2),
    system_max_torque_nm NUMERIC(8, 2),
    zero_to_hundred_seconds NUMERIC(5, 2),
    top_speed_kmh SMALLINT,
    max_ac_charge_kw NUMERIC(7, 2),
    max_dc_charge_kw NUMERIC(7, 2),
    fast_charge_minutes SMALLINT,
    fast_charge_from_percent SMALLINT,
    fast_charge_to_percent SMALLINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_car_powertrain PRIMARY KEY (id),

    CONSTRAINT uk_car_powertrain_public_id UNIQUE (public_id),
    CONSTRAINT uk_car_powertrain_model_year_code UNIQUE (model_year_id, code),
    -- variant의 복합 FK가 powertrain과 model year의 소속 일치를 DB에서 강제할 때 사용합니다.
    CONSTRAINT uk_car_powertrain_model_year_id UNIQUE (model_year_id, id),

    CONSTRAINT fk_car_powertrain_model_year FOREIGN KEY (model_year_id) REFERENCES car_model_year (id) ON DELETE RESTRICT,

    CONSTRAINT chk_car_powertrain_code CHECK (BTRIM(code) <> ''),
    CONSTRAINT chk_car_powertrain_name CHECK (BTRIM(name) <> ''),
    CONSTRAINT chk_car_powertrain_propulsion_type CHECK (
        propulsion_type IN ('ICE', 'MHEV', 'HEV', 'PHEV', 'EREV', 'BEV', 'FCEV')
    ),
    CONSTRAINT chk_car_powertrain_primary_fuel_type CHECK (
        primary_fuel_type IN ('GASOLINE', 'DIESEL', 'LPG', 'ELECTRICITY', 'HYDROGEN', 'OTHER')
    ),
    CONSTRAINT chk_car_powertrain_secondary_fuel_type CHECK (
        secondary_fuel_type IS NULL
        OR secondary_fuel_type IN ('GASOLINE', 'DIESEL', 'LPG', 'ELECTRICITY', 'HYDROGEN', 'OTHER')
    ),
    -- 외부 에너지 조합은 동력 형식과 함께 고정해 BEV·FCEV에 액체 연료가 섞이는 것을 막습니다.
    CONSTRAINT chk_car_powertrain_energy_combination CHECK (
        (propulsion_type IN ('ICE', 'MHEV', 'HEV')
            AND primary_fuel_type IN ('GASOLINE', 'DIESEL', 'LPG')
            AND secondary_fuel_type IS NULL)
        OR (propulsion_type IN ('PHEV', 'EREV')
            AND primary_fuel_type IN ('GASOLINE', 'DIESEL', 'LPG')
            AND secondary_fuel_type = 'ELECTRICITY')
        OR (propulsion_type = 'BEV'
            AND primary_fuel_type = 'ELECTRICITY'
            AND secondary_fuel_type IS NULL)
        OR (propulsion_type = 'FCEV'
            AND primary_fuel_type = 'HYDROGEN'
            AND secondary_fuel_type IS NULL)
    ),
    CONSTRAINT chk_car_powertrain_drivetrain_type CHECK (
        drivetrain_type IN ('FWD', 'RWD', 'AWD', '4WD')
    ),
    CONSTRAINT chk_car_powertrain_transmission_type CHECK (
        transmission_type IS NULL
        OR transmission_type IN ('MANUAL', 'AUTOMATIC', 'DCT', 'CVT', 'REDUCTION_GEAR', 'OTHER')
    ),
    CONSTRAINT chk_car_powertrain_transmission_gears CHECK (
        transmission_gears IS NULL OR (transmission_type IS NOT NULL AND transmission_gears > 0)
    ),
    CONSTRAINT chk_car_powertrain_positive_values CHECK (
        (system_max_power_kw IS NULL OR system_max_power_kw > 0)
        AND (system_max_power_ps IS NULL OR system_max_power_ps > 0)
        AND (system_max_torque_nm IS NULL OR system_max_torque_nm > 0)
        AND (zero_to_hundred_seconds IS NULL OR zero_to_hundred_seconds > 0)
        AND (top_speed_kmh IS NULL OR top_speed_kmh > 0)
        AND (max_ac_charge_kw IS NULL OR max_ac_charge_kw > 0)
        AND (max_dc_charge_kw IS NULL OR max_dc_charge_kw > 0)
    ),
    CONSTRAINT chk_car_powertrain_fast_charge CHECK (
        (fast_charge_minutes IS NULL
            AND fast_charge_from_percent IS NULL
            AND fast_charge_to_percent IS NULL)
        OR (fast_charge_minutes IS NOT NULL
            AND fast_charge_from_percent IS NOT NULL
            AND fast_charge_to_percent IS NOT NULL
            AND fast_charge_minutes > 0
            AND fast_charge_from_percent >= 0
            AND fast_charge_from_percent < fast_charge_to_percent
            AND fast_charge_to_percent <= 100)
    ),
    CONSTRAINT chk_car_powertrain_updated_at CHECK (updated_at >= created_at)
);

-- 이 테이블을 사용하는 첫 목록·상세 조회 경로만 보조 index로 추가합니다.
CREATE INDEX idx_car_powertrain_model_year_filter
    ON car_powertrain (model_year_id, propulsion_type, primary_fuel_type);

-- 장치 행은 한 동력계통의 엔진·모터·배터리·연료전지·탱크를 반복 가능한 구성으로 보존합니다.
CREATE TABLE car_powertrain_component (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    powertrain_id BIGINT NOT NULL,
    component_type VARCHAR(20) NOT NULL,
    component_role VARCHAR(20) NOT NULL,
    position VARCHAR(12) NOT NULL DEFAULT 'NA',
    name VARCHAR(120) NOT NULL,
    fuel_type VARCHAR(16),
    displacement_cc INTEGER,
    cylinder_count SMALLINT,
    aspiration_type VARCHAR(20),
    max_power_kw NUMERIC(8, 2),
    max_power_ps NUMERIC(8, 2),
    max_power_rpm INTEGER,
    max_torque_nm NUMERIC(8, 2),
    max_torque_kgf_m NUMERIC(8, 2),
    max_torque_rpm_from INTEGER,
    max_torque_rpm_to INTEGER,
    capacity_kwh NUMERIC(8, 2),
    capacity_ah NUMERIC(8, 2),
    voltage_v NUMERIC(8, 2),
    capacity_l NUMERIC(8, 2),
    capacity_kg NUMERIC(8, 3),
    pressure_bar NUMERIC(8, 2),
    manufacturer_name VARCHAR(120),
    cell_manufacturer_name VARCHAR(120),
    production_country_code CHAR(2),
    cell_type VARCHAR(40),
    chemistry VARCHAR(40),
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_car_powertrain_component PRIMARY KEY (id),

    CONSTRAINT uk_car_powertrain_component_identity UNIQUE (
        powertrain_id,
        component_type,
        component_role,
        position,
        name
    ),

    CONSTRAINT fk_car_powertrain_component_powertrain FOREIGN KEY (powertrain_id) REFERENCES car_powertrain (id) ON DELETE RESTRICT,

    CONSTRAINT chk_car_powertrain_component_type CHECK (
        component_type IN ('ENGINE', 'MOTOR', 'BATTERY', 'FUEL_TANK', 'FUEL_CELL', 'HYDROGEN_TANK')
    ),
    -- role 조합은 장치의 실제 책임을 고정해 엔진이나 탱크가 traction 장치로 저장되는 것을 막습니다.
    CONSTRAINT chk_car_powertrain_component_role CHECK (
        (component_type = 'ENGINE' AND component_role IN ('PRIMARY', 'RANGE_EXTENDER'))
        OR (component_type = 'MOTOR' AND component_role IN ('TRACTION', 'GENERATOR', 'STARTER_GENERATOR'))
        OR (component_type = 'BATTERY' AND component_role = 'ENERGY_STORAGE')
        OR (component_type IN ('FUEL_TANK', 'HYDROGEN_TANK') AND component_role = 'FUEL_STORAGE')
        OR (component_type = 'FUEL_CELL' AND component_role = 'PRIMARY')
    ),
    CONSTRAINT chk_car_powertrain_component_position CHECK (
        position IN ('FRONT', 'REAR', 'CENTER', 'INTEGRATED', 'NA')
    ),
    CONSTRAINT chk_car_powertrain_component_name CHECK (BTRIM(name) <> ''),
    CONSTRAINT chk_car_powertrain_component_fuel_type CHECK (
        (component_type IN ('ENGINE', 'FUEL_TANK')
            AND fuel_type IS NOT NULL
            AND fuel_type IN ('GASOLINE', 'DIESEL', 'LPG'))
        OR (component_type NOT IN ('ENGINE', 'FUEL_TANK') AND fuel_type IS NULL)
    ),
    CONSTRAINT chk_car_powertrain_component_aspiration_type CHECK (
        aspiration_type IS NULL
        OR aspiration_type IN ('NATURALLY_ASPIRATED', 'TURBO', 'SUPERCHARGED')
    ),
    CONSTRAINT chk_car_powertrain_component_positive_values CHECK (
        (displacement_cc IS NULL OR displacement_cc > 0)
        AND (cylinder_count IS NULL OR cylinder_count > 0)
        AND (max_power_kw IS NULL OR max_power_kw > 0)
        AND (max_power_ps IS NULL OR max_power_ps > 0)
        AND (max_power_rpm IS NULL OR max_power_rpm > 0)
        AND (max_torque_nm IS NULL OR max_torque_nm > 0)
        AND (max_torque_kgf_m IS NULL OR max_torque_kgf_m > 0)
        AND (max_torque_rpm_from IS NULL OR max_torque_rpm_from > 0)
        AND (max_torque_rpm_to IS NULL OR max_torque_rpm_to > 0)
        AND (capacity_kwh IS NULL OR capacity_kwh > 0)
        AND (capacity_ah IS NULL OR capacity_ah > 0)
        AND (voltage_v IS NULL OR voltage_v > 0)
        AND (capacity_l IS NULL OR capacity_l > 0)
        AND (capacity_kg IS NULL OR capacity_kg > 0)
        AND (pressure_bar IS NULL OR pressure_bar > 0)
    ),
    CONSTRAINT chk_car_powertrain_component_torque_rpm CHECK (
        max_torque_rpm_from IS NULL
        OR max_torque_rpm_to IS NULL
        OR max_torque_rpm_from <= max_torque_rpm_to
    ),
    CONSTRAINT chk_car_powertrain_component_production_country CHECK (
        production_country_code IS NULL OR production_country_code ~ '^[A-Z]{2}$'
    ),
    CONSTRAINT chk_car_powertrain_component_sort_order CHECK (sort_order >= 0),
    -- 장치 종류별 필수 용량과 전용 column을 함께 검사해 서로 다른 장치의 값이 섞이지 않게 합니다.
    CONSTRAINT chk_car_powertrain_component_type_values CHECK (
        (component_type = 'ENGINE'
            AND displacement_cc IS NOT NULL
            AND capacity_kwh IS NULL
            AND capacity_ah IS NULL
            AND voltage_v IS NULL
            AND capacity_l IS NULL
            AND capacity_kg IS NULL
            AND pressure_bar IS NULL
            AND cell_manufacturer_name IS NULL
            AND cell_type IS NULL
            AND chemistry IS NULL)
        OR (component_type = 'MOTOR'
            AND displacement_cc IS NULL
            AND cylinder_count IS NULL
            AND aspiration_type IS NULL
            AND capacity_kwh IS NULL
            AND capacity_ah IS NULL
            AND voltage_v IS NULL
            AND capacity_l IS NULL
            AND capacity_kg IS NULL
            AND pressure_bar IS NULL
            AND cell_manufacturer_name IS NULL
            AND cell_type IS NULL
            AND chemistry IS NULL)
        OR (component_type = 'BATTERY'
            AND (capacity_kwh IS NOT NULL OR capacity_ah IS NOT NULL)
            AND displacement_cc IS NULL
            AND cylinder_count IS NULL
            AND aspiration_type IS NULL
            AND capacity_l IS NULL
            AND capacity_kg IS NULL
            AND pressure_bar IS NULL)
        OR (component_type = 'FUEL_TANK'
            AND capacity_l IS NOT NULL
            AND displacement_cc IS NULL
            AND cylinder_count IS NULL
            AND aspiration_type IS NULL
            AND capacity_kwh IS NULL
            AND capacity_ah IS NULL
            AND voltage_v IS NULL
            AND capacity_kg IS NULL
            AND pressure_bar IS NULL
            AND cell_manufacturer_name IS NULL
            AND cell_type IS NULL
            AND chemistry IS NULL)
        OR (component_type = 'FUEL_CELL'
            AND max_power_kw IS NOT NULL
            AND displacement_cc IS NULL
            AND cylinder_count IS NULL
            AND aspiration_type IS NULL
            AND capacity_kwh IS NULL
            AND capacity_ah IS NULL
            AND voltage_v IS NULL
            AND capacity_l IS NULL
            AND capacity_kg IS NULL
            AND pressure_bar IS NULL
            AND cell_manufacturer_name IS NULL
            AND cell_type IS NULL
            AND chemistry IS NULL)
        OR (component_type = 'HYDROGEN_TANK'
            AND capacity_kg IS NOT NULL
            AND displacement_cc IS NULL
            AND cylinder_count IS NULL
            AND aspiration_type IS NULL
            AND capacity_kwh IS NULL
            AND capacity_ah IS NULL
            AND voltage_v IS NULL
            AND cell_manufacturer_name IS NULL
            AND cell_type IS NULL
            AND chemistry IS NULL)
    ),
    CONSTRAINT chk_car_powertrain_component_updated_at CHECK (updated_at >= created_at)
);
