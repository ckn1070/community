-- 댓글 transaction의 전달 원본입니다. Content와 독립적으로 보존해 삭제·복구 중에도 원본을 잃지 않습니다.
CREATE TABLE community_event_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE,
    event_type VARCHAR(80) NOT NULL,
    event_version INTEGER NOT NULL,
    post_id UUID NOT NULL,
    conversation_id UUID NOT NULL UNIQUE,
    payload JSONB NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    published_at TIMESTAMPTZ,
    publish_attempts INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT chk_community_outbox_contract CHECK (
        event_type = 'CommunityConversationCreated' AND event_version = 1
        AND JSONB_TYPEOF(payload) = 'object'
    ),
    CONSTRAINT chk_community_outbox_attempts CHECK (publish_attempts >= 0)
);

-- 발행 완료는 삭제 적격이 아닙니다. 미발행 원본 조회만 이 index를 사용합니다.
CREATE INDEX idx_community_outbox_unpublished ON community_event_outbox(id)
    WHERE published_at IS NULL;
