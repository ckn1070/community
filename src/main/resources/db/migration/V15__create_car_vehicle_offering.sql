-- 기술 변형은 동일 연식에서 차체·인승·휠·동력계통이 결합된 제원 단위입니다.
CREATE TABLE car_vehicle_variant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL,
    model_year_id BIGINT NOT NULL,
    powertrain_id BIGINT NOT NULL,
    code VARCHAR(80) NOT NULL,
    name VARCHAR(160) NOT NULL,
    body_type VARCHAR(16) NOT NULL,
    roof_type VARCHAR(16) NOT NULL DEFAULT 'STANDARD',
    seating_capacity SMALLINT NOT NULL,
    door_count SMALLINT,
    length_mm INTEGER NOT NULL,
    width_mm INTEGER NOT NULL,
    height_mm INTEGER NOT NULL,
    wheelbase_mm INTEGER NOT NULL,
    front_track_mm INTEGER,
    rear_track_mm INTEGER,
    ground_clearance_mm INTEGER,
    cargo_capacity_l NUMERIC(8, 2),
    max_cargo_capacity_l NUMERIC(8, 2),
    curb_weight_kg INTEGER,
    gross_vehicle_weight_kg INTEGER,
    wheel_size_inch NUMERIC(4, 1),
    front_tire VARCHAR(40),
    rear_tire VARCHAR(40),
    front_suspension VARCHAR(100),
    rear_suspension VARCHAR(100),
    steering_type VARCHAR(100),
    front_brake VARCHAR(100),
    rear_brake VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_car_vehicle_variant PRIMARY KEY (id),

    CONSTRAINT uk_car_vehicle_variant_public_id UNIQUE (public_id),
    CONSTRAINT uk_car_vehicle_variant_model_year_code UNIQUE (model_year_id, code),

    CONSTRAINT fk_car_vehicle_variant_model_year FOREIGN KEY (model_year_id) REFERENCES car_model_year (id) ON DELETE RESTRICT,
    -- 복합 FK는 variant가 다른 연식의 powertrain을 연결하지 못하게 합니다.
    CONSTRAINT fk_car_vehicle_variant_model_year_powertrain FOREIGN KEY (model_year_id, powertrain_id)
        REFERENCES car_powertrain (model_year_id, id) ON DELETE RESTRICT,

    CONSTRAINT chk_car_vehicle_variant_code CHECK (BTRIM(code) <> ''),
    CONSTRAINT chk_car_vehicle_variant_name CHECK (BTRIM(name) <> ''),
    CONSTRAINT chk_car_vehicle_variant_body_type CHECK (
        body_type IN ('SEDAN', 'HATCHBACK', 'WAGON', 'COUPE', 'CONVERTIBLE', 'SUV', 'MPV', 'PICKUP', 'VAN', 'OTHER')
    ),
    CONSTRAINT chk_car_vehicle_variant_roof_type CHECK (
        roof_type IN ('STANDARD', 'HIGH_ROOF', 'OPEN', 'OTHER')
    ),
    CONSTRAINT chk_car_vehicle_variant_positive_dimensions CHECK (
        seating_capacity > 0
        AND (door_count IS NULL OR door_count > 0)
        AND length_mm > 0
        AND width_mm > 0
        AND height_mm > 0
        AND wheelbase_mm > 0
        AND (front_track_mm IS NULL OR front_track_mm > 0)
        AND (rear_track_mm IS NULL OR rear_track_mm > 0)
        AND (ground_clearance_mm IS NULL OR ground_clearance_mm > 0)
        AND (cargo_capacity_l IS NULL OR cargo_capacity_l > 0)
        AND (max_cargo_capacity_l IS NULL OR max_cargo_capacity_l > 0)
        AND (curb_weight_kg IS NULL OR curb_weight_kg > 0)
        AND (gross_vehicle_weight_kg IS NULL OR gross_vehicle_weight_kg > 0)
        AND (wheel_size_inch IS NULL OR wheel_size_inch > 0)
    ),
    CONSTRAINT chk_car_vehicle_variant_cargo_capacity CHECK (
        cargo_capacity_l IS NULL
        OR max_cargo_capacity_l IS NULL
        OR max_cargo_capacity_l >= cargo_capacity_l
    ),
    CONSTRAINT chk_car_vehicle_variant_weight CHECK (
        curb_weight_kg IS NULL
        OR gross_vehicle_weight_kg IS NULL
        OR gross_vehicle_weight_kg >= curb_weight_kg
    ),
    CONSTRAINT chk_car_vehicle_variant_updated_at CHECK (updated_at >= created_at)
);

-- 이 테이블을 사용하는 첫 목록·상세 조회 경로만 보조 index로 추가합니다.
CREATE INDEX idx_car_variant_model_year_body
    ON car_vehicle_variant (model_year_id, body_type, powertrain_id);

-- 판매 구성은 기술 변형 아래에서 실제 트림·채널·판매 기간과 표시 전용 정보를 소유합니다.
CREATE TABLE car_configuration (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL,
    vehicle_variant_id BIGINT NOT NULL,
    code VARCHAR(80) NOT NULL,
    trim_name VARCHAR(120) NOT NULL,
    sales_channel VARCHAR(16) NOT NULL DEFAULT 'PRIVATE',
    sales_started_on DATE NOT NULL,
    sales_ended_on DATE,
    display_order INTEGER NOT NULL DEFAULT 0,
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    standard_features JSONB NOT NULL DEFAULT '[]'::JSONB,
    warranties JSONB NOT NULL DEFAULT '[]'::JSONB,
    safety_ratings JSONB NOT NULL DEFAULT '[]'::JSONB,
    media JSONB NOT NULL DEFAULT '[]'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_car_configuration PRIMARY KEY (id),

    CONSTRAINT uk_car_configuration_public_id UNIQUE (public_id),
    CONSTRAINT uk_car_configuration_variant_channel_code UNIQUE (
        vehicle_variant_id,
        sales_channel,
        code
    ),

    CONSTRAINT fk_car_configuration_vehicle_variant FOREIGN KEY (vehicle_variant_id) REFERENCES car_vehicle_variant (id) ON DELETE RESTRICT,

    CONSTRAINT chk_car_configuration_code CHECK (BTRIM(code) <> ''),
    CONSTRAINT chk_car_configuration_trim_name CHECK (BTRIM(trim_name) <> ''),
    CONSTRAINT chk_car_configuration_sales_channel CHECK (
        sales_channel IN ('PRIVATE', 'BUSINESS', 'RENTAL', 'DISABLED')
    ),
    CONSTRAINT chk_car_configuration_sales_period CHECK (
        sales_ended_on IS NULL OR sales_started_on < sales_ended_on
    ),
    CONSTRAINT chk_car_configuration_display_order CHECK (display_order >= 0),
    -- JSONB는 첫 조회에서 독립 검색하지 않는 표시 정보만 담고 최상위 배열 형식을 고정합니다.
    CONSTRAINT chk_car_configuration_standard_features CHECK (JSONB_TYPEOF(standard_features) = 'array'),
    CONSTRAINT chk_car_configuration_warranties CHECK (JSONB_TYPEOF(warranties) = 'array'),
    CONSTRAINT chk_car_configuration_safety_ratings CHECK (JSONB_TYPEOF(safety_ratings) = 'array'),
    CONSTRAINT chk_car_configuration_media CHECK (JSONB_TYPEOF(media) = 'array'),
    CONSTRAINT chk_car_configuration_updated_at CHECK (updated_at >= created_at)
);

-- 이 테이블을 사용하는 첫 목록·상세 조회 경로만 보조 index로 추가합니다.
CREATE INDEX idx_car_configuration_variant_sales
    ON car_configuration (vehicle_variant_id, sales_channel, sales_started_on, sales_ended_on)
    WHERE is_published;
