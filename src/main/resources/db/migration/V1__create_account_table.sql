CREATE TABLE account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL,
    email VARCHAR(254) NOT NULL,
    email_normalized VARCHAR(254) NOT NULL,
    status VARCHAR(20) NOT NULL,
    email_verified_at TIMESTAMPTZ,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    withdrawn_at TIMESTAMPTZ,

    CONSTRAINT pk_account PRIMARY KEY (id),

    -- public_id는 외부 API에 노출하는 안정 식별자이고, 내부 DB id를 대신합니다.
    CONSTRAINT uk_account_public_id UNIQUE (public_id),
    -- email 중복은 정규화된 값 기준으로 판단해 대소문자 차이를 허용하지 않습니다.
    CONSTRAINT uk_account_email_normalized UNIQUE (email_normalized),

    -- account 생명주기 상태는 domain enum과 DB constraint가 함께 고정합니다.
    CONSTRAINT chk_account_status CHECK (status IN ('PENDING', 'ACTIVE', 'SUSPENDED', 'WITHDRAWN')),
    -- 감사 timestamp가 역전되면 정렬과 변경 추적 기준이 깨집니다.
    CONSTRAINT chk_account_updated_at CHECK (updated_at >= created_at),
    -- 탈퇴 완료 상태에서만 탈퇴 시각을 유지합니다.
    CONSTRAINT chk_account_withdrawn_at CHECK (
        (status = 'WITHDRAWN' AND withdrawn_at IS NOT NULL)
        OR (status <> 'WITHDRAWN' AND withdrawn_at IS NULL)
    )
);
