CREATE TABLE auth_role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(50) NOT NULL,
    description VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_auth_role PRIMARY KEY (id),

    -- role code는 application/domain이 참조하는 기준 데이터 식별자입니다.
    CONSTRAINT uk_auth_role_code UNIQUE (code),

    CONSTRAINT chk_auth_role_updated_at CHECK (updated_at >= created_at),
    -- coarse-grained role은 ROLE_ prefix를 가진 대문자 code만 허용합니다.
    CONSTRAINT chk_auth_role_code CHECK (code ~ '^ROLE_[A-Z0-9_]+$')
);
