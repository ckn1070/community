CREATE TABLE refresh_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    account_public_id UUID NOT NULL,
    token_hash CHAR(64) NOT NULL,
    family_id UUID NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL,
    last_used_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    revoked_reason VARCHAR(50),
    replaced_by_token_id BIGINT,
    ip_address INET,
    user_agent VARCHAR(512),

    CONSTRAINT pk_refresh_token PRIMARY KEY (id),

    CONSTRAINT fk_refresh_token_account_public_id FOREIGN KEY (account_public_id) REFERENCES account (public_id),
    CONSTRAINT fk_refresh_token_replaced_by_token FOREIGN KEY (replaced_by_token_id) REFERENCES refresh_token (id),

    CONSTRAINT uk_refresh_token_token_hash UNIQUE (token_hash),

    -- 리프레시 토큰 원문은 저장하지 않고 해시만 저장합니다.
    CONSTRAINT chk_refresh_token_hash CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_refresh_token_expires_at CHECK (expires_at > issued_at),
    CONSTRAINT chk_refresh_token_last_used_at CHECK (last_used_at IS NULL OR last_used_at >= issued_at),
    CONSTRAINT chk_refresh_token_revoked_at CHECK (revoked_at IS NULL OR revoked_at >= issued_at),
    CONSTRAINT chk_refresh_token_revoked_reason CHECK (
        (revoked_at IS NULL AND revoked_reason IS NULL)
        OR (
            revoked_at IS NOT NULL
            AND revoked_reason IN (
                'LOGOUT',
                'ROTATED',
                'REUSE_DETECTED',
                'PASSWORD_CHANGED',
                'ACCOUNT_SUSPENDED',
                'ADMIN_REVOKED'
            )
        )
    ),
    CONSTRAINT chk_refresh_token_replaced_by CHECK (replaced_by_token_id IS NULL OR replaced_by_token_id <> id)
);

-- 계정별 활성 refresh token을 만료 시각 기준으로 찾을 때 사용합니다.
CREATE INDEX idx_refresh_token_active_account_public
    ON refresh_token (account_public_id, expires_at)
    WHERE revoked_at IS NULL;

-- token family 단위 재사용 탐지와 연쇄 폐기를 조회할 때 사용합니다.
CREATE INDEX idx_refresh_token_family_id
    ON refresh_token (family_id);

-- 만료 토큰 정리 batch가 account별 조회 없이 시간순으로 찾을 수 있게 합니다.
CREATE INDEX idx_refresh_token_expires_at
    ON refresh_token (expires_at);
