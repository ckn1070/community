CREATE TABLE account_role_assignment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    account_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    granted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    granted_by_account_id BIGINT,
    revoked_at TIMESTAMPTZ,
    revoked_by_account_id BIGINT,

    CONSTRAINT pk_account_role_assignment PRIMARY KEY (id),

    CONSTRAINT fk_account_role_assignment_account FOREIGN KEY (account_id) REFERENCES account (id),
    CONSTRAINT fk_account_role_assignment_role FOREIGN KEY (role_id) REFERENCES auth_role (id),
    CONSTRAINT fk_account_role_assignment_granted_by_account FOREIGN KEY (granted_by_account_id) REFERENCES account (id),
    CONSTRAINT fk_account_role_assignment_revoked_by_account FOREIGN KEY (revoked_by_account_id) REFERENCES account (id),

    -- 회수 주체는 실제 회수 시각이 있을 때만 남깁니다.
    CONSTRAINT chk_account_role_assignment_revoked_by CHECK (
        revoked_by_account_id IS NULL OR revoked_at IS NOT NULL
    ),
    -- role 회수 이력은 부여 시각보다 앞설 수 없습니다.
    CONSTRAINT chk_account_role_assignment_revoked_at CHECK (
        revoked_at IS NULL OR revoked_at >= granted_at
    )
);

-- 활성 역할 부여는 하나만 허용하고, 회수 이력은 다시 부여할 수 있습니다.
CREATE UNIQUE INDEX uk_account_role_assignment_active_account_role
    ON account_role_assignment (account_id, role_id)
    WHERE revoked_at IS NULL;

-- 특정 role을 가진 활성 account 목록을 조회할 때 사용합니다.
CREATE INDEX idx_account_role_assignment_active_role
    ON account_role_assignment (role_id, account_id)
    WHERE revoked_at IS NULL;
