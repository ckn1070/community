-- Community의 게시판, 콘텐츠 subtype과 반응 무결성 경계를 추가합니다.
CREATE TABLE community_board (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL,
    slug VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT pk_community_board PRIMARY KEY (id),
    CONSTRAINT uk_community_board_public_id UNIQUE (public_id),
    CONSTRAINT uk_community_board_slug UNIQUE (slug),
    CONSTRAINT chk_community_board_version CHECK (version >= 0),
    CONSTRAINT chk_community_board_time CHECK (updated_at >= created_at)
);

-- Content root는 post와 comment가 공유하는 공개 식별자, 작성자와 visibility 사실을 소유합니다.
CREATE TABLE community_content (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL,
    kind VARCHAR(20) NOT NULL,
    account_public_id UUID NOT NULL,
    board_id BIGINT,
    post_content_id BIGINT,
    parent_comment_id BIGINT,
    thread_root_comment_id BIGINT,
    creation_request_id UUID NOT NULL,
    creation_request_hash CHAR(64) NOT NULL,
    edited_at TIMESTAMPTZ,
    author_deleted_at TIMESTAMPTZ,
    moderator_hidden_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT pk_community_content PRIMARY KEY (id),
    CONSTRAINT uk_community_content_public_id UNIQUE (public_id),
    CONSTRAINT uk_community_content_creation UNIQUE (account_public_id, creation_request_id),
    CONSTRAINT fk_community_content_account FOREIGN KEY (account_public_id) REFERENCES account(public_id) ON DELETE RESTRICT,
    CONSTRAINT fk_community_content_board FOREIGN KEY (board_id) REFERENCES community_board(id),
    CONSTRAINT fk_community_content_post FOREIGN KEY (post_content_id) REFERENCES community_content(id),
    CONSTRAINT fk_community_content_parent FOREIGN KEY (parent_comment_id) REFERENCES community_content(id),
    CONSTRAINT fk_community_content_root FOREIGN KEY (thread_root_comment_id) REFERENCES community_content(id),
    CONSTRAINT chk_community_content_kind CHECK (kind IN ('POST', 'COMMENT')),
    CONSTRAINT chk_community_content_shape CHECK (
        (kind = 'POST' AND board_id IS NOT NULL AND post_content_id IS NULL AND parent_comment_id IS NULL AND thread_root_comment_id IS NULL)
        OR
        (kind = 'COMMENT' AND board_id IS NULL AND post_content_id IS NOT NULL AND
          ((parent_comment_id IS NULL AND thread_root_comment_id IS NULL) OR
           (parent_comment_id IS NOT NULL AND thread_root_comment_id IS NOT NULL)))
    ),
    CONSTRAINT chk_community_content_request_hash CHECK (creation_request_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_community_content_version CHECK (version >= 0),
    CONSTRAINT chk_community_content_time CHECK (updated_at >= created_at)
);

-- Post subtype은 제목, canonical body와 목록 preview를 같은 row에서 원자적으로 보존합니다.
CREATE TABLE community_post (
    content_id BIGINT,
    title VARCHAR(120) NOT NULL,
    body_preview VARCHAR(200) NOT NULL,
    body_schema_version SMALLINT NOT NULL,
    body JSONB NOT NULL,

    CONSTRAINT pk_community_post PRIMARY KEY (content_id),
    CONSTRAINT fk_community_post_content FOREIGN KEY (content_id) REFERENCES community_content(id),
    CONSTRAINT chk_community_post_title CHECK (
        CHAR_LENGTH(title) BETWEEN 1 AND 120 AND title = BTRIM(title)
        AND title !~ '[[:cntrl:]]' AND title !~ '  '
    ),
    CONSTRAINT chk_community_post_preview CHECK (
        CHAR_LENGTH(body_preview) BETWEEN 1 AND 200 AND body_preview = BTRIM(body_preview)
        AND body_preview !~ '[[:cntrl:]]' AND body_preview !~ '  '
    ),
    CONSTRAINT chk_community_post_body CHECK (
        body_schema_version = 1 AND JSONB_TYPEOF(body) = 'object'
        AND JSONB_TYPEOF(body -> 'blocks') = 'array'
    )
);

-- Comment subtype은 정규화된 plain text만 저장합니다.
CREATE TABLE community_comment (
    content_id BIGINT,
    body TEXT NOT NULL,

    CONSTRAINT pk_community_comment PRIMARY KEY (content_id),
    CONSTRAINT fk_community_comment_content FOREIGN KEY (content_id) REFERENCES community_content(id),
    CONSTRAINT chk_community_comment_body CHECK (CHAR_LENGTH(BTRIM(body)) BETWEEN 1 AND 2000)
);

-- 한 account는 한 content에 하나의 reaction만 가지며 PUT으로 그 값을 교체합니다.
CREATE TABLE community_reaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    content_id BIGINT NOT NULL,
    account_public_id UUID NOT NULL,
    reaction_type VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_community_reaction PRIMARY KEY (id),
    CONSTRAINT uk_community_reaction_actor UNIQUE (content_id, account_public_id),
    CONSTRAINT fk_community_reaction_content FOREIGN KEY (content_id) REFERENCES community_content(id),
    CONSTRAINT fk_community_reaction_account FOREIGN KEY (account_public_id) REFERENCES account(public_id) ON DELETE RESTRICT,
    CONSTRAINT chk_community_reaction_type CHECK (reaction_type IN ('LIKE', 'DISLIKE')),
    CONSTRAINT chk_community_reaction_time CHECK (updated_at >= created_at)
);

-- Self FK가 표현하지 못하는 subtype과 같은-post parent/root 불변식을 commit 시점에 검증합니다.
CREATE FUNCTION validate_community_content_shape() RETURNS TRIGGER AS $$
DECLARE
    post_kind VARCHAR(20);
    parent_kind VARCHAR(20);
    parent_post_id BIGINT;
    root_kind VARCHAR(20);
    root_post_id BIGINT;
    root_parent_id BIGINT;
    post_subtype_count INTEGER;
    comment_subtype_count INTEGER;
BEGIN
    SELECT COUNT(*) INTO post_subtype_count FROM community_post WHERE content_id = NEW.id;
    SELECT COUNT(*) INTO comment_subtype_count FROM community_comment WHERE content_id = NEW.id;
    IF (NEW.kind = 'POST' AND (post_subtype_count <> 1 OR comment_subtype_count <> 0))
       OR (NEW.kind = 'COMMENT' AND (post_subtype_count <> 0 OR comment_subtype_count <> 1)) THEN
        RAISE EXCEPTION 'content subtype must exactly match content kind';
    END IF;
    IF NEW.kind = 'COMMENT' THEN
        SELECT kind INTO post_kind FROM community_content WHERE id = NEW.post_content_id;
        IF post_kind IS DISTINCT FROM 'POST' THEN
            RAISE EXCEPTION 'comment post target must be POST';
        END IF;
        IF NEW.parent_comment_id IS NOT NULL THEN
            SELECT kind, post_content_id INTO parent_kind, parent_post_id FROM community_content WHERE id = NEW.parent_comment_id;
            SELECT kind, post_content_id, parent_comment_id INTO root_kind, root_post_id, root_parent_id FROM community_content WHERE id = NEW.thread_root_comment_id;
            IF parent_kind IS DISTINCT FROM 'COMMENT' OR parent_post_id IS DISTINCT FROM NEW.post_content_id
               OR root_kind IS DISTINCT FROM 'COMMENT' OR root_post_id IS DISTINCT FROM NEW.post_content_id
               OR root_parent_id IS NOT NULL THEN
                RAISE EXCEPTION 'comment parent/root must belong to the same post and root must be top-level';
            END IF;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trg_community_content_shape
AFTER INSERT OR UPDATE OF kind, post_content_id, parent_comment_id, thread_root_comment_id
ON community_content DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION validate_community_content_shape();

CREATE FUNCTION validate_community_subtype_shape() RETURNS TRIGGER AS $$
DECLARE
    target_id BIGINT;
    target_kind VARCHAR(20);
    post_subtype_count INTEGER;
    comment_subtype_count INTEGER;
BEGIN
    target_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.content_id ELSE NEW.content_id END;
    SELECT kind INTO target_kind FROM community_content WHERE id = target_id;
    SELECT COUNT(*) INTO post_subtype_count FROM community_post WHERE content_id = target_id;
    SELECT COUNT(*) INTO comment_subtype_count FROM community_comment WHERE content_id = target_id;
    IF target_kind IS NULL
       OR (target_kind = 'POST' AND (post_subtype_count <> 1 OR comment_subtype_count <> 0))
       OR (target_kind = 'COMMENT' AND (post_subtype_count <> 0 OR comment_subtype_count <> 1)) THEN
        RAISE EXCEPTION 'subtype row must exactly match content kind';
    END IF;
    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trg_community_post_subtype_shape
AFTER INSERT OR UPDATE OR DELETE ON community_post DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION validate_community_subtype_shape();

CREATE CONSTRAINT TRIGGER trg_community_comment_subtype_shape
AFTER INSERT OR UPDATE OR DELETE ON community_comment DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION validate_community_subtype_shape();

