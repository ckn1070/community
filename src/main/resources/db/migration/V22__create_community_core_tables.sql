-- 공개 목록, 대화, reaction 집계와 소유자 mutation의 실제 query 순서를 지원합니다.
CREATE INDEX idx_community_content_visible_posts ON community_content (board_id, created_at DESC, id DESC)
WHERE kind = 'POST' AND author_deleted_at IS NULL AND moderator_hidden_at IS NULL;
CREATE INDEX idx_community_content_top_comments ON community_content (post_content_id, created_at DESC, id DESC)
WHERE kind = 'COMMENT' AND parent_comment_id IS NULL;
CREATE INDEX idx_community_content_replies ON community_content (thread_root_comment_id, created_at, id)
WHERE kind = 'COMMENT' AND thread_root_comment_id IS NOT NULL;
CREATE INDEX idx_community_content_owner ON community_content (account_public_id, public_id);
CREATE INDEX idx_community_content_post_fk ON community_content (post_content_id);
CREATE INDEX idx_community_content_parent_fk ON community_content (parent_comment_id);
CREATE INDEX idx_community_content_root_fk ON community_content (thread_root_comment_id);
CREATE INDEX idx_community_reaction_count ON community_reaction (content_id, reaction_type);
