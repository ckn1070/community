-- 신차 카탈로그 schema는 기존 account/auth 객체를 변경하지 않는 expand-only migration입니다.
-- 11개 테이블은 제품 계층, 동력 장치, 판매 구성, 가격·옵션 이력과 조건별 인증을 분리해 보존합니다.

-- 브랜드는 여러 모델이 공유하는 최상위 제품 분류입니다.
CREATE TABLE car_brand (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL,
    code VARCHAR(40) NOT NULL,
    name_ko VARCHAR(80) NOT NULL,
    name_en VARCHAR(80),
    country_code CHAR(2) NOT NULL,
    homepage_url TEXT,
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_car_brand PRIMARY KEY (id),

    CONSTRAINT uk_car_brand_public_id UNIQUE (public_id),
    CONSTRAINT uk_car_brand_code UNIQUE (code),

    CONSTRAINT chk_car_brand_code CHECK (BTRIM(code) <> ''),
    CONSTRAINT chk_car_brand_name_ko CHECK (BTRIM(name_ko) <> ''),
    CONSTRAINT chk_car_brand_name_en CHECK (name_en IS NULL OR BTRIM(name_en) <> ''),
    CONSTRAINT chk_car_brand_country_code CHECK (country_code ~ '^[A-Z]{2}$'),
    CONSTRAINT chk_car_brand_homepage_url CHECK (homepage_url IS NULL OR BTRIM(homepage_url) <> ''),
    CONSTRAINT chk_car_brand_display_order CHECK (display_order >= 0),
    CONSTRAINT chk_car_brand_updated_at CHECK (updated_at >= created_at)
);

-- 모델은 세대가 바뀌어도 유지되는 브랜드 내부 검색·표시 단위입니다.
CREATE TABLE car_model (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL,
    brand_id BIGINT NOT NULL,
    code VARCHAR(60) NOT NULL,
    name_ko VARCHAR(100) NOT NULL,
    name_en VARCHAR(100),
    name_normalized VARCHAR(100) NOT NULL,
    summary TEXT,
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_car_model PRIMARY KEY (id),

    CONSTRAINT uk_car_model_public_id UNIQUE (public_id),
    CONSTRAINT uk_car_model_brand_code UNIQUE (brand_id, code),
    CONSTRAINT uk_car_model_brand_name_normalized UNIQUE (brand_id, name_normalized),

    CONSTRAINT fk_car_model_brand FOREIGN KEY (brand_id) REFERENCES car_brand (id) ON DELETE RESTRICT,

    CONSTRAINT chk_car_model_code CHECK (BTRIM(code) <> ''),
    CONSTRAINT chk_car_model_name_ko CHECK (BTRIM(name_ko) <> ''),
    CONSTRAINT chk_car_model_name_en CHECK (name_en IS NULL OR BTRIM(name_en) <> ''),
    CONSTRAINT chk_car_model_name_normalized CHECK (BTRIM(name_normalized) <> ''),
    CONSTRAINT chk_car_model_display_order CHECK (display_order >= 0),
    CONSTRAINT chk_car_model_updated_at CHECK (updated_at >= created_at)
);

-- 세대는 모델 아래에서 full change와 상품성 변경 단계를 순서대로 보존합니다.
CREATE TABLE car_generation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL,
    model_id BIGINT NOT NULL,
    code VARCHAR(60) NOT NULL,
    name VARCHAR(120) NOT NULL,
    generation_order SMALLINT NOT NULL,
    change_type VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_car_generation PRIMARY KEY (id),

    CONSTRAINT uk_car_generation_public_id UNIQUE (public_id),
    CONSTRAINT uk_car_generation_model_code UNIQUE (model_id, code),
    CONSTRAINT uk_car_generation_model_order UNIQUE (model_id, generation_order),

    CONSTRAINT fk_car_generation_model FOREIGN KEY (model_id) REFERENCES car_model (id) ON DELETE RESTRICT,

    CONSTRAINT chk_car_generation_code CHECK (BTRIM(code) <> ''),
    CONSTRAINT chk_car_generation_name CHECK (BTRIM(name) <> ''),
    CONSTRAINT chk_car_generation_order CHECK (generation_order > 0),
    CONSTRAINT chk_car_generation_change_type CHECK (
        change_type IN ('FULL_CHANGE', 'FACELIFT', 'MINOR_CHANGE')
    ),
    CONSTRAINT chk_car_generation_updated_at CHECK (updated_at >= created_at)
);

-- 모델 연식은 한 시장에서 동일 세대의 사양과 판매 기간이 유지되는 edition입니다.
CREATE TABLE car_model_year (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_id UUID NOT NULL,
    generation_id BIGINT NOT NULL,
    market_code CHAR(2) NOT NULL DEFAULT 'KR',
    model_year SMALLINT NOT NULL,
    edition_code VARCHAR(40) NOT NULL,
    display_name VARCHAR(120) NOT NULL,
    released_on DATE,
    sales_started_on DATE NOT NULL,
    sales_ended_on DATE,
    summary TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_car_model_year PRIMARY KEY (id),

    CONSTRAINT uk_car_model_year_public_id UNIQUE (public_id),
    CONSTRAINT uk_car_model_year_generation_market_year_edition UNIQUE (
        generation_id,
        market_code,
        model_year,
        edition_code
    ),

    CONSTRAINT fk_car_model_year_generation FOREIGN KEY (generation_id) REFERENCES car_generation (id) ON DELETE RESTRICT,

    CONSTRAINT chk_car_model_year_market_code CHECK (market_code ~ '^[A-Z]{2}$'),
    CONSTRAINT chk_car_model_year_year CHECK (model_year BETWEEN 1950 AND 2100),
    CONSTRAINT chk_car_model_year_edition_code CHECK (BTRIM(edition_code) <> ''),
    CONSTRAINT chk_car_model_year_display_name CHECK (BTRIM(display_name) <> ''),
    CONSTRAINT chk_car_model_year_sales_period CHECK (
        sales_ended_on IS NULL OR sales_started_on < sales_ended_on
    ),
    CONSTRAINT chk_car_model_year_updated_at CHECK (updated_at >= created_at)
);
